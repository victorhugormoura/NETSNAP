def texto_grande(alvo):
    base = [t for _, t, _ in SEGREDOS if "-----BEGIN" not in t] + [t for _, t, _ in PRESERVAR] + BENIGNAS
    linhas, tam, i = [], 0, 0
    while tam < alvo:
        if i % 20 == 0:
            l = base[(i // 20) % len(base)]
        else:
            l = (f"set interfaces ge-0/0/{i % 48} unit {i} family inet address "
                 f"10.{i % 250}.{i % 200}.1/30" if i % 3 else
                 f"zone \"dominio{i}.com.br\" {{ type master; file \"/etc/bind/db.local\"; }};")
        linhas.append(l)
        tam += len(l) + 1
        i += 1
    return "\n".join(linhas)


def main():
    args = [a for a in sys.argv[1:]]
    orig = None
    if "--orig" in args:
        k = args.index("--orig")
        orig = args[k + 1]
        del args[k:k + 2]
    alvo = args[0] if args else os.path.join(AQUI, "..", "netsnap.py")
    ns = carregar(alvo, "ns_teste")
    falhas = []

    for cid, texto, segs in SEGREDOS:
        out = ns.sanitizar(texto)
        vaz = [s for s in segs if s in out]
        if vaz:
            falhas.append(f"FN {cid}: {vaz} sobreviveu em {out!r}")
    for cid, texto, manter in PRESERVAR:
        out = ns.sanitizar(texto)
        perd = [m for m in manter if m not in out]
        if perd:
            falhas.append(f"FP {cid}: perdeu {perd} -> {out!r}")
    for linha in BENIGNAS:
        out = ns.sanitizar(linha)
        if out != linha:
            falhas.append(f"FP benigna: {linha!r} -> {out!r}")
    # Idempotência: sanitizar duas vezes não muda o resultado.
    for cid, texto, _ in SEGREDOS:
        uma = ns.sanitizar(texto)
        if ns.sanitizar(uma) != uma:
            falhas.append(f"idempotencia {cid}: {uma!r}")
    # Alinhamento com U+0130 (único caractere cujo lower() muda de tamanho).
    t = "descricao \u0130STANBUL-POP\nsnmp-server community SegredoTurco RO\npassword=Outro1"
    out = ns.sanitizar(t)
    if "SegredoTurco" in out or "Outro1" in out or "\u0130STANBUL-POP" not in out:
        falhas.append(f"U+0130: {out!r}")

    # Desempenho: configuração de 12 MB.
    grande = texto_grande(12_000_000)
    t0 = time.perf_counter()
    ns.sanitizar(grande)
    seg = time.perf_counter() - t0
    print(f"sanitizar(12 MB): {seg:.2f}s ({alvo})")
    if orig:
        ref = carregar(orig, "ns_ref")
        t0 = time.perf_counter()
        ref.sanitizar(grande)
        seg_ref = time.perf_counter() - t0
        print(f"sanitizar(12 MB) referencia: {seg_ref:.2f}s ({orig})")
        if seg > seg_ref * 1.25:
            falhas.append(f"desempenho: {seg:.2f}s contra {seg_ref:.2f}s da referencia")
    elif seg > 10:
        falhas.append(f"desempenho: {seg:.2f}s para 12 MB")
    # Entradas adversariais (retrocesso catastrófico): cada uma < 3 s.
    adversariais = {
        "qualificadores": ("password " + "aes 1 " * 50 + "=\n") * 7000,
        "linha longa": ("radius tacacs isakmp mysql sshpass curl snmp-server host 1.1.1.1 "
                        + "traps " * 40 + "x" * 50 + " ") * 6000,
        "sem quebra": "a" * 2_000_000,
        "dois-pontos": ("http://a:b:c:d:e:f:g:h:i:j:k" * 20 + "\n") * 8000,
        "authentication-mode": ("authentication-mode " + "x " * 200 + "\n") * 5000,
        "chaves": ("passwordpassword secret secret key key \"" * 30 + "\n") * 1100,
        "dolar": ("$1$" + "a" * 7 + " ") * 180000,
    }
    for nome, txt in adversariais.items():
        t0 = time.perf_counter()
        ns.sanitizar(txt)
        d = time.perf_counter() - t0
        if d > 3:
            falhas.append(f"adversarial '{nome}': {d:.2f}s")

    total = len(SEGREDOS) + len(PRESERVAR) + len(BENIGNAS)
    if falhas:
        print(f"FALHOU: {len(falhas)} verificacao(oes) de {total} casos")
        for f in falhas:
            print("  " + f)
        sys.exit(1)
    print(f"OK: {len(SEGREDOS)} segredos removidos, {len(PRESERVAR)} trechos e "
          f"{len(BENIGNAS)} linhas benignas preservados; idempotente; sem retrocesso catastrofico")


if __name__ == "__main__":
    main()
